"""
================================================================
  CutWise IMS - AI Chat View (RAG Pipeline)
  Capstone 2: AI Service — Gemini LLM Integration

  Architecture Mapping (Arch 1):
    Analytics/AI Layer -> AI Service -> LLM Integration -> NL Queries

  Pipeline:
    User Question
      -> [1] Embed with sentence-transformers (all-MiniLM-L6-v2)
      -> [2] ChromaDB semantic search (top 5 materials)
      -> [3] Fetch KPI summary from analytics.db
      -> [4] Build context + system prompt
      -> [5] Gemini 1.5 Flash generates answer
      -> [6] Return { reply, sources[], model }

  Endpoint:
    POST /api/v1/analytics/chat/
    Body: { "message": "Which materials need reorder?" }
    Auth: Bearer JWT (IsAuthenticated)
================================================================
"""

import os
import sqlite3
import logging
from pathlib import Path

from rest_framework.decorators import api_view, permission_classes
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response
from rest_framework import status

logger = logging.getLogger(__name__)

BASE_DIR        = Path(__file__).resolve().parent.parent.parent
SQLITE_PATH     = BASE_DIR / "data" / "analytics.db"
CHROMA_DIR      = BASE_DIR / "data" / "chroma_db"
COLLECTION_NAME = "cutwise_materials"

# ─── Module-level singletons (loaded once at startup, not per request) ────────

_chroma_collection = None   # ChromaDB collection handle
_embed_model       = None   # SentenceTransformer model
_gemini_client     = None   # Gemini API client


_chroma_count_cache = 0  # tracks last known doc count; non-zero triggers refresh if changed


def _get_chroma_collection():
    """
    Return (and cache) the ChromaDB collection.
    Auto-refreshes the handle when the doc count changes after a vector rebuild —
    so Django doesn't need a restart after running vector_db.py.
    """
    global _chroma_collection, _chroma_count_cache
    try:
        import chromadb
        client = chromadb.PersistentClient(path=str(CHROMA_DIR))
        col = client.get_collection(COLLECTION_NAME)
        current_count = col.count()

        # Refresh if first load OR if collection was rebuilt with new docs
        if _chroma_collection is None or current_count != _chroma_count_cache:
            _chroma_collection = col
            _chroma_count_cache = current_count
            logger.info(f"ChromaDB collection loaded/refreshed: {current_count} documents")

    except Exception as e:
        logger.warning(f"ChromaDB not available: {e}")
        _chroma_collection = None

    return _chroma_collection



def _get_embed_model():
    """Return (and cache) the SentenceTransformer model. Loaded once on first call."""
    global _embed_model
    if _embed_model is not None:
        return _embed_model
    try:
        from sentence_transformers import SentenceTransformer
        _embed_model = SentenceTransformer("all-MiniLM-L6-v2")
        logger.info("SentenceTransformer model loaded")
    except ImportError:
        logger.warning("sentence-transformers not available — will use SQLite fallback")
        _embed_model = None
    return _embed_model


def _get_gemini_client():
    """Return (and cache) the Gemini API client. Created once on first call."""
    global _gemini_client
    if _gemini_client is not None:
        return _gemini_client
    api_key = os.environ.get("GEMINI_API_KEY", "")
    if not api_key:
        return None
    try:
        from google import genai
        _gemini_client = genai.Client(api_key=api_key)
        logger.info("Gemini client initialized")
    except Exception as e:
        logger.error(f"Gemini client init failed: {e}")
        _gemini_client = None
    return _gemini_client


